def overlay(parts,system,key,width):
 """Append patches inside the original nested SVG before route annotations."""
 reference,records=LABELS[key];unit=width/reference
 for x,y,w,h,value,bg,fg in records:
  lines=value.split('|');size=min(24,h/(len(lines)*1.25),w/max(len(line) for line in lines)*.92)
  text_x=x+w/2
  if key=='daimarub1' and x==918:
   text_x=x+42;size=min(size,76/max(len(line) for line in lines))
  # Sweet-zone pills match the accepted v1.30 treatment.
  if key=='b1' and x==1028 and y in (684,998):
   parts.append(f'<g class="translated-zone" data-label="{escape(value,quote=True)}"><rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#fff"/><rect x="{x}" y="{y}" width="{w}" height="33" rx="16" fill="#0863b5"/>')
   system(lines[0],x+w/2,y+23,23,WHITE,'middle');system(lines[1],x+w/2,y+53,21,'#26312e','middle');parts.append('</g>');continue
  parts.append(f'<g class="translated-zone" data-label="{escape(value,quote=True)}"><rect x="{x*unit:.3f}" y="{y*unit:.3f}" width="{w*unit:.3f}" height="{h*unit:.3f}" fill="{bg}"/>')
  for i,line in enumerate(lines):
   baseline=y+h/2+(i-(len(lines)-1)/2)*size*1.25+size*.34
   system(line,text_x*unit,baseline*unit,size*unit,fg,'middle')
  parts.append('</g>')
